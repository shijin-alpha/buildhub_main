/**
 * Get climate profile for a panchayat/municipality.
 * Falls back to district-level defaults if panchayat not found.
 */
export const getClimateProfile = (locationName, districtName) => {
  if (locationName && panchayatClimateData[locationName]) {
    return panchayatClimateData[locationName];
  }
  // District-level fallback
  const districtDefaults = {
    'Thiruvananthapuram': c('moderate', 'midland',  'low'),
    'Kollam':             c('high',     'coastal',  'moderate'),
    'Pathanamthitta':     c('high',     'midland',  'low'),
    'Alappuzha':          c('high',     'backwater','high'),
    'Kottayam':           c('high',     'midland',  'low'),
    'Idukki':             c('very_high','highland', 'low'),
    'Ernakulam':          c('high',     'flat',     'moderate'),
    'Thrissur':           c('high',     'flat',     'moderate'),
    'Palakkad':           c('low',      'flat',     'low',      'high'),
    'Malappuram':         c('high',     'flat',     'moderate'),
    'Kozhikode':          c('high',     'coastal',  'moderate'),
    'Wayanad':            c('very_high','highland', 'low'),
    'Kannur':             c('high',     'coastal',  'moderate'),
    'Kasaragod':          c('high',     'coastal',  'moderate'),
  };
  return districtDefaults[districtName] || c('high', 'flat', 'low');
};

/**
 * Convert climate profile to numeric risk modifiers for the ML predictor.
 * Returns { cost_mod, time_mod, flood_mod } as percentage adjustments (0-25).
 */
export const climateToRiskModifiers = (profile) => {
  const rainfallMod = { very_high: 20, high: 10, moderate: 0, low: -5 };
  const terrainMod  = { highland: 18, hilly: 12, midland: 5, coastal: 8, backwater: 15, flat: 0 };
  const floodMod    = { high: 15, moderate: 8, low: 0 };
  const heatMod     = { high: 8, moderate: 3, low: 0 };

  const rain  = rainfallMod[profile.rainfall]  ?? 0;
  const terr  = terrainMod[profile.terrain]    ?? 0;
  const flood = floodMod[profile.flood_risk]   ?? 0;
  const heat  = heatMod[profile.heat_risk]     ?? 0;

  return {
    cost_mod: Math.round((rain * 0.4 + terr * 0.3 + flood * 0.2 + heat * 0.1)),
    time_mod: Math.round((rain * 0.3 + terr * 0.4 + flood * 0.3)),
    flood_mod: flood,
    terrain_label: profile.terrain,
    rainfall_label: profile.rainfall,
  };
};
